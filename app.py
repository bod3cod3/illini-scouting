@st.cache_data
def load_data():
    """
    Load Four Factors data and cache it

    Streamlit reruns the whole file when changes occur, so this prevents unnecessary re-downloading
    """
    four_factors = load_torvik_four_factors(SEASON_YEAR)
    four_factors = add_percentile_columns(four_factors)

    return four_factors


def write_bullet_section(title: str, items: list[str], empty_message: str) -> None:
    """
    Display a report section with bullet points

    If list is empty, show fallback message
    """
    st.subheader(title)

    if len(items) == 0:
        st.write(f"- {empty_message}")
        return

    for item in items:
        st.write(f"- {item}")


def write_matchup_score_explanation() -> None:
    """
    Explain how base favorability should be interpreted
    """
    with st.expander("How to read base favorability", expanded=False):
        st.write(
            "Base favorability is a 0-100 score from the selected base team's perspective. "
            "Higher is better for the base team. Lower is worse for the base team."
        )

        st.write(
            "For opponent pressure areas, the score compares the base team's resistance metric "
            "against the opponent's attacking metric. For base team edge areas, it compares "
            "the base team's attacking metric against the opponent's resistance metric."
        )

        st.write(
            "A score near 100 means the matchup strongly favors the base team. "
            "A score near 50 is closer to neutral. A score near 0 means the matchup strongly favors the opponent."
        )


def write_supporting_stats_table(rows: list[dict]) -> None:
    """
    Display compact supporting stats behind the matchup engine
    """
    st.subheader("Supporting stats")
    st.caption("Base favorability is always from the selected base team's perspective. Higher is better.")

    if len(rows) == 0:
        st.write("No supporting stats generated by the matchup engine.")
        return

    table = pd.DataFrame(rows)

    base_team_name = table["base_team"].iloc[0]
    opponent_name = table["opponent"].iloc[0]

    base_metric_col = f"{base_team_name} metric"
    base_percentile_col = f"{base_team_name} percentile"
    opponent_metric_col = f"{opponent_name} metric"
    opponent_percentile_col = f"{opponent_name} percentile"

    table = table.rename(
        columns={
            "area": "Area",
            "direction": "Matchup lens",
            "matchup_type": "Type",
            "base_favorability_score": "Base favorability",
            "base_metric_display_name": base_metric_col,
            "base_percentile": base_percentile_col,
            "opponent_metric_display_name": opponent_metric_col,
            "opponent_percentile": opponent_percentile_col,
        }
    )

    table = table[
        [
            "Area",
            "Base favorability",
            "Matchup lens",
            "Type",
            base_metric_col,
            base_percentile_col,
            opponent_metric_col,
            opponent_percentile_col,
        ]
    ]

    st.dataframe(
        table,
        hide_index=True,
        width="stretch",
        column_config={
            "Base favorability": st.column_config.NumberColumn(
                "Base favorability",
                format="%.1f",
            ),
            base_percentile_col: st.column_config.NumberColumn(
                base_percentile_col,
                format="%.1f",
            ),
            opponent_percentile_col: st.column_config.NumberColumn(
                opponent_percentile_col,
                format="%.1f",
            ),
        },
    )

def write_matchup_favorability_chart(rows: list[dict], team_colors: dict) -> None:
    """
    Display a vertical bar chart of base favorability by matchup area
    """
    st.subheader("Matchup favorability profile")
    st.caption("Higher bars are better for the selected base team.")

    if len(rows) == 0:
        st.write("No matchup favorability data available.")
        return

    chart_data = pd.DataFrame(rows)
    chart_data = chart_data.sort_values(
        by="base_favorability_score",
        ascending=False,
    )

    primary = team_colors["primary"]
    secondary = team_colors["secondary"]

    fig = go.Figure()

    fig.add_trace(
        go.Bar(
            x=chart_data["area"],
            y=chart_data["base_favorability_score"],
            marker={
                "color": primary,
                "line": {
                    "color": secondary,
                    "width": 1.5,
                },
            },
            text=chart_data["base_favorability_score"],
            texttemplate="%{text:.1f}",
            textposition="outside",
            hovertemplate=(
                "<b>%{x}</b><br>"
                "Base favorability: %{y:.1f}/100"
                "<extra></extra>"
            ),
        )
    )

    fig.update_layout(
        height=430,
        margin={
            "l": 20,
            "r": 20,
            "t": 20,
            "b": 90,
        },
        yaxis={
            "range": [0, 105],
            "title": "Base favorability",
            "gridcolor": "rgba(255, 255, 255, 0.12)",
        },
        xaxis={
            "title": "",
            "tickangle": -30,
        },
        plot_bgcolor="rgba(0, 0, 0, 0)",
        paper_bgcolor="rgba(0, 0, 0, 0)",
        font={
            "color": "white",
        },
        showlegend=False,
    )

    st.plotly_chart(fig, use_container_width=True)

